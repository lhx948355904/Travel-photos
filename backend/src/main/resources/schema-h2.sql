ALTER TABLE photo_embedding ADD COLUMN IF NOT EXISTS analysis_model VARCHAR(128);
ALTER TABLE photo_embedding ADD COLUMN IF NOT EXISTS embedding_model VARCHAR(128);
ALTER TABLE photo_embedding ADD COLUMN IF NOT EXISTS retry_count INT DEFAULT 0 NOT NULL;
ALTER TABLE photo_embedding ADD COLUMN IF NOT EXISTS index_error TEXT;
ALTER TABLE photo_embedding ADD COLUMN IF NOT EXISTS content_hash VARCHAR(64);
ALTER TABLE photo_embedding ADD COLUMN IF NOT EXISTS indexed_at TIMESTAMP;
ALTER TABLE photo_embedding ADD COLUMN IF NOT EXISTS next_retry_at TIMESTAMP;

CREATE INDEX IF NOT EXISTS idx_photo_embedding_user ON photo_embedding (user_id);
