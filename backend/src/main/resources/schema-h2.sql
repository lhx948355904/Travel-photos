CREATE TABLE IF NOT EXISTS blog_category (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    name VARCHAR(64) NOT NULL,
    slug VARCHAR(80) NOT NULL,
    display_order INT NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_blog_category_user FOREIGN KEY (user_id) REFERENCES app_user(id),
    CONSTRAINT uk_blog_category_user_slug UNIQUE (user_id, slug)
);

CREATE TABLE IF NOT EXISTS blog_tag (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    name VARCHAR(32) NOT NULL,
    slug VARCHAR(48) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_blog_tag_user FOREIGN KEY (user_id) REFERENCES app_user(id),
    CONSTRAINT uk_blog_tag_user_slug UNIQUE (user_id, slug)
);

CREATE TABLE IF NOT EXISTS blog_asset (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    object_key VARCHAR(512) NOT NULL,
    original_name VARCHAR(255),
    content_type VARCHAR(128),
    width INT,
    height INT,
    fallback_url VARCHAR(1024),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT fk_blog_asset_user FOREIGN KEY (user_id) REFERENCES app_user(id),
    CONSTRAINT uk_blog_asset_object_key UNIQUE (object_key)
);

CREATE TABLE IF NOT EXISTS blog_post (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    category_id BIGINT,
    cover_asset_id BIGINT,
    title VARCHAR(160) NOT NULL DEFAULT '',
    slug VARCHAR(180) NOT NULL,
    excerpt VARCHAR(320),
    content_markdown CLOB NOT NULL DEFAULT '',
    status VARCHAR(16) NOT NULL DEFAULT 'DRAFT',
    published_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT fk_blog_post_user FOREIGN KEY (user_id) REFERENCES app_user(id),
    CONSTRAINT fk_blog_post_category FOREIGN KEY (category_id) REFERENCES blog_category(id),
    CONSTRAINT fk_blog_post_cover FOREIGN KEY (cover_asset_id) REFERENCES blog_asset(id),
    CONSTRAINT uk_blog_post_user_slug UNIQUE (user_id, slug),
    CONSTRAINT ck_blog_post_status CHECK (status IN ('DRAFT', 'PUBLISHED'))
);

CREATE TABLE IF NOT EXISTS blog_post_tag (
    post_id BIGINT NOT NULL,
    tag_id BIGINT NOT NULL,
    CONSTRAINT pk_blog_post_tag PRIMARY KEY (post_id, tag_id),
    CONSTRAINT fk_blog_post_tag_post FOREIGN KEY (post_id) REFERENCES blog_post(id) ON DELETE CASCADE,
    CONSTRAINT fk_blog_post_tag_tag FOREIGN KEY (tag_id) REFERENCES blog_tag(id)
);

CREATE INDEX IF NOT EXISTS idx_blog_post_public ON blog_post (user_id, status, published_at);
CREATE INDEX IF NOT EXISTS idx_blog_post_category ON blog_post (category_id, status, published_at);
CREATE INDEX IF NOT EXISTS idx_blog_asset_user_deleted ON blog_asset (user_id, deleted);
CREATE INDEX IF NOT EXISTS idx_blog_post_tag_tag ON blog_post_tag (tag_id, post_id);
